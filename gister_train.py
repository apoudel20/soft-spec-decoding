"""Gister v2: train the stage-2 search network on live target forward passes over much more on-policy text.

Gister = stage-1 gist VAE (frozen, ae_gate.py gist_hf_z2048) + stage-2 search network (stage2.Search with raw
target-state input). v1 trained stage 2 on 482K cached chunk pairs from 2,000 answers and a 154M network overfit.
Here nothing is cached: each step runs the frozen 4-bit target over a few conversations, takes its states at layers
18, 24, 30 and the final normed state for every response position plus its own top-1 tokens, z-scores them with the
cache stats, encodes context and next chunks with the frozen stage-1 encoder, and trains stage 2 on many chunk
pairs from those conversations.

Data: Qwen3-8B's own non-thinking answers. PerfectBlend regenerated by Qwen3-8B (heiheiha798/perfectblend-regen-
qwen3-8b-non-thinking, shard 0, first user turn and first assistant turn) plus our 2,000 answers continued to 1,024
tokens (q3_train*_long). Labels are always the 4-bit target's own top-1 at each position (teacher-forced).

Dev: the same cached dev rounds as stage2.py (dev_math / dev_code / dev_chat, accepted per round out of 9), run
every --eval_every steps, so overfitting shows as dev falling while train CE keeps dropping. The best dev
checkpoint is kept.

Run:    python gister_train.py [--d 1024 --depth 12] [--hours 2.5] [--smoke]
Output: ckpt/stage2_gister_v2.pt (stage2.py checkpoint format, loads in e2e.py), results/gister_v2.json
"""
import argparse
import json
import os
import random
import time

import numpy as np
import torch
import torch.nn.functional as F
from transformers import AutoTokenizer

from ae_gate import CKPT, Data
from common import DATA, RES, load_items
from dflash_eval import TARGET_ID, load_target
from stage2 import Search, load_stage1

K = 8
LAYERS = [18, 24, 30, 36]


def load_convs(tok, n_pb, max_resp=1024, max_prompt=512, own=True):
    import pyarrow.parquet as pq
    out = []
    for name in (("q3_train_long", "q3_train_more_long") if own else ()):
        out += [{"prompt": x["prompt"], "resp": x["resp"][:max_resp]} for x in load_items(name)]
    n_own = len(out)
    p = os.path.join(DATA, "ext", "perfectblend", "data", "train-00000-of-00008.parquet")
    rows = pq.read_table(p, columns=["conversations"]).slice(0, n_pb).to_pylist()
    end = tok.convert_tokens_to_ids("<|im_end|>")
    for r in rows:
        c = r["conversations"]
        if len(c) < 2 or c[0]["role"] != "user" or c[1]["role"] != "assistant":
            continue
        pr = tok(tok.apply_chat_template([c[0]], tokenize=False, add_generation_prompt=True, enable_thinking=False),
                 add_special_tokens=False).input_ids
        rs = tok(c[1]["content"], add_special_tokens=False).input_ids + [end]
        if len(pr) > max_prompt or len(rs) < 3 * K:
            continue
        out.append({"prompt": pr, "resp": rs[:max_resp]})
    print(f"conversations: {n_own} own + {len(out) - n_own} PerfectBlend, "
          f"{sum(len(x['resp']) for x in out) / 1e6:.1f}M response tokens", flush=True)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ae", default="gist_hf_z2048")
    ap.add_argument("--init_norm", default="stage2_gist_hf_z2048_det_raw", help="stage-2 ckpt whose zm/zs to reuse")
    ap.add_argument("--d", type=int, default=1024)
    ap.add_argument("--depth", type=int, default=12)
    ap.add_argument("--lr", type=float, default=3e-4)
    ap.add_argument("--B", type=int, default=128)
    ap.add_argument("--seqs", type=int, default=4, help="conversations per target forward batch")
    ap.add_argument("--per_seq", type=int, default=96, help="chunk pairs sampled per conversation")
    ap.add_argument("--lat_w", type=float, default=1.0)
    ap.add_argument("--n_pb", type=int, default=60000)
    ap.add_argument("--hours", type=float, default=2.5)
    ap.add_argument("--steps", type=int, default=0, help="if > 0, stop after this many optimizer steps")
    ap.add_argument("--eval_every", type=int, default=2000)
    ap.add_argument("--eval_rounds", type=int, default=300, help="dev rounds per set during training (0 = all)")
    ap.add_argument("--name", default="gister_v2")
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    if args.smoke:
        args.n_pb, args.steps, args.eval_every, args.name = 200, 40, 20, args.name + "_smoke"
    dev = "cuda"
    tok = AutoTokenizer.from_pretrained(TARGET_ID)
    convs = load_convs(tok, args.n_pb)
    t = load_target()
    for p in t.parameters():
        p.requires_grad_(False)
    ae, a, cache, layers, stats, W = load_stage1(args.ae, dev)
    assert torch.equal(W[:8], t.lm_head.weight[:8])
    del W
    torch.cuda.empty_cache()
    W = t.lm_head.weight                                       # one copy of the 1.2 GB head, shared with the target
    assert layers == LAYERS
    st = [(m.to(dev), s.to(dev), mk.to(dev)) for m, s, mk in stats]
    fm, fs = st[-1][0], st[-1][1]
    R, nq, D = len(layers), ae.nq, W.shape[1]
    fin = slice((R - 1) * K, R * K)
    ck = torch.load(os.path.join(CKPT, f"{args.init_norm}.pt"), map_location="cpu")
    zm, zs = ck["zm"].to(dev), ck["zs"].to(dev)
    net = Search(nq, ae.zq, args.d, args.depth, 1, R * K, D).to(dev)
    print(f"search params {sum(p.numel() for p in net.parameters()) / 1e6:.1f}M", flush=True)
    import bitsandbytes as bnb
    opt = bnb.optim.AdamW8bit(net.parameters(), lr=args.lr, weight_decay=0.01)    # 8-bit state to fit beside the target

    def logp(x):
        return (x.to(torch.bfloat16) @ W.T).float().log_softmax(-1)

    def encode(x):                              # x (B, R*K, D) z-scored -> normalised latent (B, nq, zq)
        hf = W[logp(x[:, fin] * fs + fm).argmax(-1)].float()
        with torch.autocast("cuda", torch.bfloat16):
            return (ae.encode(x, None, hf)[0].float() - zm) / zs

    def dec_final(zn):
        with torch.autocast("cuda", torch.bfloat16):
            return ae.decode(zn * zs + zm).float()[:, fin] * fs + fm

    @torch.no_grad()
    def harvest(batch):                         # live target pass -> (xc, zc, zt, lab) for sampled chunk pairs
        xs, labs = [], []
        for it in batch:
            ids = torch.tensor([it["prompt"] + it["resp"]], device=dev)
            n0, n = len(it["prompt"]), ids.shape[1]
            hs = t.model(input_ids=ids, output_hidden_states=True).hidden_states   # no full-vocab logits
            sl = slice(n0 - 1, n - 1)                       # states that predict the response tokens
            rows = n - n0
            if rows < 2 * K:
                continue
            top1 = torch.cat([(hs[36][0, sl][i:i + 512] @ W.T).argmax(-1) for i in range(0, rows, 512)])
            s0 = torch.randperm(rows - 2 * K + 1, device=dev)[:args.per_seq]
            idx = s0[:, None] + torch.arange(2 * K, device=dev)[None]            # (P, 16)
            g = []
            for l, (m, s, mk) in zip(LAYERS, st):
                x = (hs[l][0, sl][idx].float() - m) / s                          # (P, 16, D), sampled rows only
                x[..., mk] = 0
                g.append(x.to(torch.bfloat16))
            del hs
            xs.append(torch.stack(g, 1))                                          # (P, R, 16, D) bf16
            labs.append(top1[idx[:, K:]])
        x = torch.cat(xs)
        del xs
        xc = x[:, :, :K].flatten(1, 2).float()
        xt = x[:, :, K:].flatten(1, 2)
        zc = torch.cat([encode(xc[i:i + 256]) for i in range(0, len(xc), 256)])
        zt = torch.cat([encode(xt[i:i + 256].float()) for i in range(0, len(xt), 256)])
        return xc, zc, zt, torch.cat(labs)

    # dev: the cached rounds stage2.py scores
    devsets = {}
    for sp in ["dev_math", "dev_code", "dev_chat"]:
        dt = Data(cache, sp, layers, K, stats)
        Z = torch.load(os.path.join(DATA, "zcache", f"{args.ae}_{sp}.pt"))
        top1 = np.load(os.path.join(cache, f"{sp}_meta.npz"))["top1"].astype(np.int64)
        n = len(dt.seq)
        valid = np.zeros(n, bool)
        valid[dt.starts] = True
        pair = np.zeros(n, bool)
        pair[:n - K] = valid[:n - K] & valid[K:] & (dt.seq[:n - K] == dt.seq[K:])
        keep, last = [], -10 ** 9
        for s in np.nonzero(pair)[0]:
            if s >= last + 2 * K:
                keep.append(s)
                last = s
        keep = np.array(keep)
        devsets[sp] = (dt, Z, top1, keep[:args.eval_rounds] if args.eval_rounds else keep)

    @torch.no_grad()
    def evaluate():
        net.eval()
        out = {}
        for sp, (dt, Z, top1, keep) in devsets.items():
            acc, ce = [], []
            for i in range(0, len(keep), 128):
                s = keep[i:i + 128]
                xc = dt.get(s)[0].to(dev)
                zc = (Z[s].float().to(dev) - zm) / zs
                z1 = net(zc, torch.zeros_like(zc), torch.zeros(len(s), device=dev), xc)
                lab = torch.from_numpy(top1[(s + K)[:, None] + np.arange(K)]).to(dev)
                lq = logp(dec_final(z1))
                ce.append(F.nll_loss(lq.flatten(0, 1), lab.flatten(), reduction="none").view(len(s), K).mean(1))
                acc.append((lq.argmax(-1) == lab).int().cumprod(1).sum(1) + 1)
            out[sp] = {"accepted": torch.cat(acc).float().mean().item(), "ce": torch.cat(ce).mean().item()}
        net.train()
        return out

    rng = random.Random(0)
    order = list(range(len(convs)))
    rng.shuffle(order)
    ptr, step, t0, log, best = 0, 0, time.time(), [], -1.0
    total_steps = args.steps or 10 ** 9
    sched_len = args.steps or 20000                            # cosine length; time cap may stop earlier
    seen_tok = 0
    net.train()
    while step < total_steps and (time.time() - t0) / 3600 < args.hours:
        batch = [convs[order[(ptr + i) % len(order)]] for i in range(args.seqs)]
        ptr += args.seqs
        seen_tok += sum(len(b["resp"]) for b in batch)
        xc, zc, zt, lab = harvest(batch)
        perm = torch.randperm(len(xc), device=dev)
        for j in range(0, len(perm) - args.B + 1, args.B):
            b = perm[j:j + args.B]
            lr = args.lr * min(1, (step + 1) / 500) * max(0.1, 0.5 * (1 + np.cos(np.pi * min(1, step / sched_len))))
            for gr in opt.param_groups:
                gr["lr"] = lr
            with torch.autocast("cuda", torch.bfloat16):
                z1 = net(zc[b], torch.zeros_like(zc[b]), torch.zeros(len(b), device=dev), xc[b]).float()
            lat = F.mse_loss(z1, zt[b])
            ce = F.nll_loss(logp(dec_final(z1)).flatten(0, 1), lab[b].flatten())
            loss = ce + args.lat_w * lat
            opt.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(net.parameters(), 1.0)
            opt.step()
            step += 1
            if step % 250 == 0 or step == 1:
                print(json.dumps({"step": step, "ce": round(ce.item(), 4), "lat": round(lat.item(), 4),
                                  "convs": ptr, "resp_tok_M": round(seen_tok / 1e6, 2),
                                  "min": round((time.time() - t0) / 60, 1)}), flush=True)
            if step % args.eval_every == 0:
                ev = evaluate()
                r = {"step": step, "train_ce": ce.item(), "convs": ptr, "resp_tok_M": seen_tok / 1e6,
                     "min": (time.time() - t0) / 60, **{f"{k}_acc": v["accepted"] for k, v in ev.items()},
                     **{f"{k}_ce": v["ce"] for k, v in ev.items()}}
                log.append(r)
                print("EVAL", json.dumps({k: (round(v, 3) if isinstance(v, float) else v) for k, v in r.items()}),
                      flush=True)
                score = np.mean([v["accepted"] for v in ev.values()])
                if score > best:
                    best = score
                    sa = {"d": args.d, "depth": args.depth, "hist": 1, "raw": True, "ae": args.ae, "mode": "det",
                          "steps": step, "source": "gister_train"}
                    torch.save({"model": net.state_dict(), "args": sa, "zm": zm.cpu(), "zs": zs.cpu()},
                               os.path.join(CKPT, f"stage2_{args.name}.pt"))
                json.dump({"args": vars(args), "log": log, "best_mean_accepted": best},
                          open(os.path.join(RES, f"{args.name}.json"), "w"), indent=1)
            if step >= total_steps:
                break
    ev = evaluate()
    print("FINAL", json.dumps({k: round(v["accepted"], 3) for k, v in ev.items()}), f"best mean {best:.3f}",
          f"{(time.time() - t0) / 60:.1f} min", flush=True)
    print(f"=== gister_train {args.name} done", flush=True)


if __name__ == "__main__":
    main()
